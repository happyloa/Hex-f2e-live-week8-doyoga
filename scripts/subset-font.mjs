import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const source = new URL("../src/", import.meta.url);
const output = new URL("lib/fonts/", source);
const remote =
  "https://raw.githubusercontent.com/adobe-fonts/source-han-sans/2.005R/Variable/WOFF2/TTF/Subset/SourceHanSansTW-VF.ttf.woff2";
const printableAscii = Array.from({ length: 95 }, (_, index) =>
  String.fromCodePoint(0x20 + index),
);
const glyphs = new Set(printableAscii);

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const location = new URL(
      `${entry.name}${entry.isDirectory() ? "/" : ""}`,
      directory,
    );
    if (entry.isDirectory()) await collect(location);
    else if (/\.(?:ts|svelte|html)$/.test(entry.name)) {
      const content = await readFile(location, "utf8");
      for (const character of content.match(/[^\x00-\x7f\s]/gu) ?? [])
        glyphs.add(character);
    }
  }
}

await collect(source);
const points = [...glyphs]
  .map((character) => character.codePointAt(0))
  .sort((a, b) => a - b);
const printable = points.map((point) => String.fromCodePoint(point)).join("");
const ranges = [
  "U+20-7E",
  ...points
    .filter((point) => point > 0x7e)
    .map((point) => `U+${point.toString(16).toUpperCase()}`),
];

const localFont = process.argv[2];
let font;
if (localFont) font = await readFile(localFont);
else {
  const response = await fetch(remote, { signal: AbortSignal.timeout(120000) });
  if (!response.ok)
    throw new Error(`Source Han Sans TW download returned ${response.status}`);
  font = Buffer.from(await response.arrayBuffer());
}

const subset = await subsetFont(font, printable, {
  targetFormat: "truetype",
  variationAxes: { wght: { min: 300, default: 400, max: 700 } },
});
const renameScript = fileURLToPath(
  new URL("./rename-font.py", import.meta.url),
);
const python =
  process.env.DOYOGA_FONT_PYTHON ||
  (process.platform === "win32" ? "python" : "python3");
const renamed = spawnSync(python, [renameScript], { input: subset });
if (renamed.error) throw renamed.error;
if (renamed.status !== 0) throw new Error(renamed.stderr.toString());
const result = await subsetFont(renamed.stdout, undefined, {
  targetFormat: "woff2",
  keepAllGlyphs: true,
});

await mkdir(output, { recursive: true });
await writeFile(new URL("ui.woff2", output), result);
await writeFile(
  new URL("ui.css", output),
  [
    "/* Generated by npm run font:subset. */",
    "@font-face {",
    "  font-family: 'DOYOGA Han Sans';",
    "  src: url('./ui.woff2') format('woff2');",
    "  font-style: normal;",
    "  font-weight: 300 700;",
    "  font-display: swap;",
    `  unicode-range: ${ranges.join(", ")};`,
    "}",
    "",
  ].join("\n"),
);
console.log(
  `Source Han Sans TW subset: ${glyphs.size} code points, ${result.byteLength} bytes`,
);
