import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import subsetFont from 'subset-font';

const source = new URL('../src/', import.meta.url);
const output = new URL('lib/fonts/', source);
const revision = 'b950a7257470b900078f2bf3223823a8602de7e1';
const remote = `https://raw.githubusercontent.com/google/fonts/${revision}/ofl/notosanstc/NotoSansTC%5Bwght%5D.ttf`;
const printableAscii = Array.from({ length: 95 }, (_, index) => String.fromCodePoint(0x20 + index));
const glyphs = new Set(printableAscii);

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const location = new URL(`${entry.name}${entry.isDirectory() ? '/' : ''}`, directory);
    if (entry.isDirectory()) await collect(location);
    else if (/\.(?:ts|svelte|html)$/.test(entry.name)) {
      const content = await readFile(location, 'utf8');
      for (const character of content.match(/[^\x00-\x7f\s]/gu) ?? []) glyphs.add(character);
    }
  }
}

await collect(source);
const points = [...glyphs].map((character) => character.codePointAt(0)).sort((a, b) => a - b);
const printable = points.map((point) => String.fromCodePoint(point)).join('');
const ranges = [
  'U+20-7E',
  ...points.filter((point) => point > 0x7e).map((point) => `U+${point.toString(16).toUpperCase()}`),
];

const localFont = process.argv[2];
let font;
if (localFont) font = await readFile(localFont);
else {
  const response = await fetch(remote, { signal: AbortSignal.timeout(60000) });
  if (!response.ok) throw new Error(`Noto Sans TC download returned ${response.status}`);
  font = Buffer.from(await response.arrayBuffer());
}

const result = await subsetFont(font, printable, {
  targetFormat: 'woff2',
  variationAxes: { wght: { min: 400, default: 400, max: 700 } },
});

await mkdir(output, { recursive: true });
await writeFile(new URL('ui.woff2', output), result);
await writeFile(
  new URL('ui.css', output),
  [
    '/* Generated by npm run font:subset. */',
    '@font-face {',
    "  font-family: 'DOYOGA Noto Sans TC';",
    "  src: url('./ui.woff2') format('woff2');",
    '  font-style: normal;',
    '  font-weight: 400 700;',
    '  font-display: swap;',
    `  unicode-range: ${ranges.join(', ')};`,
    '}',
    '',
  ].join('\n'),
);
console.log(`Noto Sans TC subset: ${glyphs.size} code points, ${result.byteLength} bytes`);
